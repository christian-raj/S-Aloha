public record CiRelationshipView(
    int Id,
    int SourceId,
    CiSummary? Source,
    int TargetId,
    CiSummary? Target,
    string? Type)
{
    public static CiRelationshipView From(CiRelationship e) => new(
        e.Id,
        e.SourceId,
        CiSummary.Of(e.Source),
        e.TargetId,
        CiSummary.Of(e.Target),
        e.Type);
}

