namespace SAloha.Api.Modules.IncidentManagement;

// Réponses de l'API (A2, ADR-0016) : DTO explicites, noms de champs inchangés pour le frontend.
// Un champ ajouté à une entité n'est exposé qu'en l'ajoutant ici.

public record IncidentView(
    string? Impact,
    string? Urgency,
    string? Priority,
    string? Category,
    string? AffectedService,
    int? ServiceId,
    bool IsMajor,
    string? Resolution,
    string? ResolutionCode,
    DateTime? FirstResponseAt,
    DateTime? ResolvedAt,
    DateTime? ClosedAt,
    int ReopenCount,
    DateTime? OccurredAt,
    DateTime? ResolutionDueAt,
    DateTime? ResponseDueAt,
    bool OwnerChanged,
    bool? FirstContactResolution,
    string? ReopenReason,
    string? OnHoldReason,
    DateTime? OnHoldSince,
    int HeldMinutes,
    string? SlaState,
    int Id,
    int PerimeterId,
    string? Reference,
    string? Title,
    string? Description,
    string? Status,
    string? OwnerType,
    string? OwnerId,
    string? OwnerDisplayName,
    string? CreatedBy,
    string? CreatedByDisplayName,
    DateTime CreatedAt,
    DateTime UpdatedAt)
{
    public static IncidentView From(Incident e) => new(
        e.Impact,
        e.Urgency,
        e.Priority,
        e.Category,
        e.AffectedService,
        e.ServiceId,
        e.IsMajor,
        e.Resolution,
        e.ResolutionCode,
        e.FirstResponseAt,
        e.ResolvedAt,
        e.ClosedAt,
        e.ReopenCount,
        e.OccurredAt,
        e.ResolutionDueAt,
        e.ResponseDueAt,
        e.OwnerChanged,
        e.FirstContactResolution,
        e.ReopenReason,
        e.OnHoldReason,
        e.OnHoldSince,
        e.HeldMinutes,
        e.SlaState,
        e.Id,
        e.PerimeterId,
        e.Reference,
        e.Title,
        e.Description,
        e.Status,
        e.OwnerType,
        e.OwnerId,
        e.OwnerDisplayName,
        e.CreatedBy,
        e.CreatedByDisplayName,
        e.CreatedAt,
        e.UpdatedAt);
}
